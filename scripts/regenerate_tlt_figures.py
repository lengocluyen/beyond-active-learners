def _zero_note(ax, text, y=0.045):
    """Label series that are identically zero instead of hiding them."""
    ax.annotate(text, xy=(0.5, y), xycoords=("axes fraction", "data"),
                ha="center", va="bottom", fontsize=6.0, color=INK)

def budget_response() -> None:
    budget = read_csv(OULAD / "budget_performance.csv")
    protocols = ["cutoff_valid", "activity_to_cutoff_valid", "activity_conditioned"]
    labels = {
        "cutoff_valid": "Cutoff-valid",
        "activity_to_cutoff_valid": "Activity-trained, valid-scored",
        "activity_conditioned": "Activity-conditioned",
    }
    fig, axes = plt.subplots(2, 2, figsize=(7.16, 4.45), sharex=True)
    for col, week in enumerate([2, 16]):
        frame = budget[budget.week.eq(week)]
        for protocol in protocols:
            d = (
                frame[frame.protocol.eq(protocol)]
                .groupby("budget")
                .agg(
                    actionable_precision=("actionable_precision", "median"),
                    waste=("wasted_budget_rate", "median"),
                )
            )
            x = 100 * d.index.to_numpy()
            style = SERIES_STYLE[protocol]
            axes[0, col].plot(x, d.actionable_precision, label=labels[protocol], **style)
            axes[1, col].plot(x, d.waste, **style)
        # Both valid-scored protocols sit exactly on zero; the thick-solid under
        # thin-dashed pairing keeps them separable, and the note removes any
        # doubt that two series are present rather than one.
        _zero_note(axes[1, col], "both valid-scored protocols $\\equiv 0$", y=0.025)
        axes[0, col].set_title(f"({'a' if col == 0 else 'b'}) Eligibility-adjusted precision, wk {week}")
        axes[1, col].set_title(f"({'c' if col == 0 else 'd'}) Noneligible allocation, wk {week}")
        axes[1, col].set_xlabel("Intervention budget (%)")
        for row in range(2):
            axes[row, col].set_ylim(-0.03, 1.03)
            axes[row, col].set_xticks([1, 5, 10, 20])
            axes[row, col].grid(alpha=0.25, linewidth=0.5)
            axes[row, col].spines[["top", "right"]].set_visible(False)
    axes[0, 0].set_ylabel("Precision")
    axes[1, 0].set_ylabel("Proportion")
    handles, legend_labels = axes[0, 0].get_legend_handles_labels()
    fig.legend(handles, legend_labels, ncol=3, frameon=False, loc="lower center")
    fig.tight_layout(rect=(0, 0.07, 1, 1), h_pad=1.4, w_pad=1.5)
    save(fig, "fig7_budget_response")

def _hazard_prevalence() -> pd.DataFrame:
    """Recover the seven-day label directly from the saved eligible roster."""
    frame = read_csv(OULAD / "cohort_membership.csv.gz")
    frame = frame.loc[frame.cutoff_valid].copy()
    if frame.duplicated(["week", "id_student", "code_module", "code_presentation"]).any():
        raise ValueError("Duplicate enrolment-landmark rows in cohort membership")
    frame["hazard_event"] = (
        frame.date_unregistration.ge(frame.cutoff_day)
        & frame.date_unregistration.lt(frame.cutoff_day + 7)
    ).astype(int)
    return (
        frame.groupby("week")
        .hazard_event.agg(event_rate="mean", n="size")
        .rename_axis("week")
        .reset_index()
    )

def hazard_benchmark() -> None:
    summary = read_csv(OULAD_HAZARD / "discrete_hazard_summary.csv")
    auc = summary.groupby("week").auc_mean.agg(
        median="median", q1=lambda s: s.quantile(0.25), q3=lambda s: s.quantile(0.75)
    )
    full = summary[summary.model.eq("stack_7_full")].set_index("week")
    prevalence = _hazard_prevalence().set_index("week")
    if not np.array_equal(summary.n.to_numpy(), summary.week.map(prevalence.n).to_numpy()):
        raise ValueError("Hazard summary counts differ from saved eligible roster")
    # Separate size and prevalence axes avoid suggesting a relationship through
    # independently adjustable scales on a dual-axis plot.
    fig, axes = plt.subplots(1, 3, figsize=(7.16, 2.6),
                             gridspec_kw={"width_ratios": [1.55, 1, 1]})
    ax = axes[0]
    ax.fill_between(auc.index, auc.q1, auc.q3, color=BLUE, alpha=0.18,
                    linewidth=0, label="Model IQR")
    ax.plot(auc.index, auc["median"], "o-", color=BLUE, label="Model median")
    ax.errorbar(full.index, full.auc_mean,
                yerr=[full.auc_mean-full.auc_ci_low, full.auc_ci_high-full.auc_mean],
                fmt="s-", color=RED, capsize=2, label="Rich stack (95% CI)")
    ax.set(title="(a) Withdrawal discrimination", ylabel="ROC-AUC", ylim=(0.5, 0.9))
    ax.legend(frameon=False, loc="lower right", fontsize=6)
    axes[1].plot(prevalence.index, prevalence.n/1000, "s-", color=GREEN)
    axes[1].set(title="(b) Eligible population", ylabel="Enrolments (thousands)")
    axes[2].plot(prevalence.index, 100*prevalence.event_rate, "o--", color=ORANGE)
    axes[2].set(title="(c) Seven-day events", ylabel="Withdrawal in next 7 days (%)")
    for ax in axes:
        ax.set_xlabel("Landmark week")
        ax.set_xticks([2, 8, 16])
        ax.grid(alpha=0.25, linewidth=0.5)
        ax.spines[["top", "right"]].set_visible(False)
    fig.tight_layout(w_pad=1.5)
    save(fig, "fig8_hazard_benchmark")

def _selected_predictions() -> pd.DataFrame:
    path = OULAD / "predictions.csv.gz"
    usecols = ["week", "protocol", "model", "risk", "risk_score"]
    pieces = []
    checkpoints = [OULAD / "checkpoints" / f"week_{week:03d}__stack_7_full.csv.gz"
                   for week in (2, 16)]
    if all(checkpoint.is_file() for checkpoint in checkpoints):
        chunks = (read_csv(checkpoint, usecols=usecols) for checkpoint in checkpoints)
    else:
        chunks = read_csv(path, usecols=usecols, chunksize=250_000)
    for chunk in chunks:
        selected = chunk[
            chunk.model.eq("stack_7_full")
            & chunk.week.isin([2, 16])
            & chunk.protocol.isin(["activity_conditioned", "cutoff_valid", "static_full"])
        ]
        if not selected.empty:
            pieces.append(selected)
    return pd.concat(pieces, ignore_index=True)

def calibration_profiles() -> None:
    frame = _selected_predictions()
    protocols = ["cutoff_valid", "activity_conditioned", "static_full"]
    labels = {
        "cutoff_valid": "Cutoff-valid",
        "activity_conditioned": "Activity-conditioned",
        "static_full": "Static-full",
    }
    colors = {
        "cutoff_valid": GREEN,
        "activity_conditioned": BLUE,
        "static_full": PURPLE,
    }
    fig, axes = plt.subplots(1, 2, figsize=(7.16, 2.85))
    for ax, week, panel in zip(axes, [2, 16], ["a", "b"]):
        for protocol in protocols:
            d = frame[frame.week.eq(week) & frame.protocol.eq(protocol)].copy()
            d["bin"] = pd.qcut(d.risk_score, q=10, duplicates="drop")
            curve = d.groupby("bin", observed=True).agg(
                predicted=("risk_score", "mean"), observed=("risk", "mean"), n=("risk", "size")
            )
            marker = {"cutoff_valid": "o", "activity_conditioned": "s", "static_full": "^"}[protocol]
            dash = {"cutoff_valid": "-", "activity_conditioned": "--", "static_full": ":"}[protocol]
            ax.plot(curve.predicted, curve.observed, marker=marker, linestyle=dash,
                    color=colors[protocol], label=labels[protocol])
        ax.plot([0, 1], [0, 1], "--", color="black", linewidth=0.8)
        ax.set(
            title=f"({panel}) Full-stack calibration, week {week}",
            xlabel="Mean predicted adverse-outcome risk",
            ylabel="Observed adverse-outcome rate",
            xlim=(0, 1),
            ylim=(0, 1),
        )
        ax.grid(alpha=0.25, linewidth=0.5)
        ax.spines[["top", "right"]].set_visible(False)
    axes[0].legend(frameon=False, loc="upper left")
    fig.tight_layout(w_pad=2.0)
    save(fig, "fig9_calibration_profiles")


def parse_args():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--results", type=Path, required=True,
                        help="OULAD results with protocol.json or fit_protocol_original.json")
    parser.add_argument("--output-dir", type=Path, default=Path("paper_tlt_riskset/figures"))
    parser.add_argument("--extra", action="store_true", help="Also regenerate supporting figures 5-9")
    return parser.parse_args()


def main():
    global OULAD, OULAD_HAZARD, OUT
    args = parse_args()
    OULAD = args.results.expanduser().resolve()
    OULAD_HAZARD = OULAD
    OUT = args.output_dir.expanduser().resolve()
    protocol_path = OULAD / "protocol.json"
    if not protocol_path.is_file():
        protocol_path = OULAD / "fit_protocol_original.json"
    protocol = json.loads(protocol_path.read_text(encoding="utf-8"))
    if protocol.get("dataset") != "oulab":
        raise ValueError("This figure suite requires an OULAD result directory")
    if args.extra and protocol.get("hazard_days") != 7:
        raise ValueError("Supporting hazard figures require a seven-day interval")
    INPUTS.add(protocol_path)
    required = ["cohort_composition.csv", "training_evaluation_decomposition.csv",
                "budget_performance.csv", "decision_overlap.csv"]
    if args.extra:
        required += ["excluded_profile_categorical.csv", "metric_distortion.csv",
                     "discrete_hazard_summary.csv", "cohort_membership.csv.gz"]
    missing = [name for name in required if not (OULAD / name).is_file()]
    if missing:
        raise FileNotFoundError("Missing figure inputs: " + ", ".join(missing))
    style()

def _median_band(ax, frame, metric, color, label, contrast=None, linestyle="-"):
    d = frame[frame.metric.eq(metric)]
    if contrast is not None:
        d = d[d.contrast.eq(contrast)]
    g = d.groupby("week").delta.agg(
        median="median", q1=lambda s: s.quantile(0.25), q3=lambda s: s.quantile(0.75)
    )
    marker = {"joint_population_difference": "o", "evaluation_population_shapley": "s",
              "training_population_shapley": "^"}.get(contrast, "o")
    ax.plot(g.index, g["median"], marker=marker, linestyle=linestyle, color=color, label=label)
    ax.fill_between(g.index, g.q1, g.q3, color=color, alpha=0.18, linewidth=0)

def _path_span(ax, frame, metric, color, contrast_a, contrast_b):
    """Shade between the two traversals of the 2x2 design.

    This is the range between path-specific medians across configurations,
    not a confidence interval or the median cellwise interaction.
    """
    d = frame[frame.metric.eq(metric)]
    a = d[d.contrast.eq(contrast_a)].groupby("week").delta.median()
    b = d[d.contrast.eq(contrast_b)].groupby("week").delta.median()
    joined = pd.concat([a, b], axis=1, keys=["a", "b"]).dropna()
    ax.fill_between(
        joined.index,
        joined[["a", "b"]].min(axis=1),
        joined[["a", "b"]].max(axis=1),
        color=color,
        alpha=0.30,
        linewidth=0,
    )

def metric_distortion() -> None:
    od = read_csv(OULAD / "training_evaluation_decomposition.csv")
    fig, axes = plt.subplots(1, 2, figsize=(7.16, 2.55))
    contrasts = [
        ("joint_population_difference", BLUE, "Joint: A→A minus V→V", "-"),
        ("evaluation_population_shapley", RED, "Evaluation (symmetric)", "-"),
        ("training_population_shapley", GREEN, "Training (symmetric)", "--"),
    ]
    spans = [
        (
            RED,
            "evaluation_population_component",
            "evaluation_population_component_at_valid",
        ),
        (
            GREEN,
            "training_population_component",
            "training_population_component_at_activity",
        ),
    ]
    for ax, metric, title in zip(
        axes,
        ["auc", "pr_auc_risk"],
        ["(a) ROC-AUC decomposition", "(b) Adverse-outcome PR-AUC decomposition"],
    ):
        for color, contrast_a, contrast_b in spans:
            _path_span(ax, od, metric, color, contrast_a, contrast_b)
        for contrast, color, label, linestyle in contrasts:
            _median_band(ax, od, metric, color, label, contrast, linestyle)
        ax.set(title=title, xlabel="Landmark week", ylabel="Raw metric difference")
        ax.xaxis.set_major_locator(MaxNLocator(integer=True))
        ax.legend(frameon=False, loc="best", fontsize=6)

    for ax in axes:
        ax.axhline(0, color="black", linewidth=0.7)
        ax.grid(alpha=0.25, linewidth=0.5)
        ax.spines[["top", "right"]].set_visible(False)
    fig.tight_layout(w_pad=2.0)
    save(fig, "fig3_metric_distortion")

def decision_distortion() -> None:
    ob = read_csv(OULAD / "budget_performance.csv")
    ob = ob[
        ob.protocol.eq("activity_conditioned")
        & ob.reference_protocol.eq("cutoff_valid")
        & ob.budget.eq(0.05)
    ]
    oo = read_csv(OULAD / "decision_overlap.csv")
    oo = oo[oo.budget.eq(0.05)]

    fig, axes = plt.subplots(1, 2, figsize=(7.16, 2.55))
    overlap_specs = [
        ("protocol", "activity_conditioned", "cutoff_valid", BLUE, "Joint: A→A vs V→V"),
        ("evaluation_population", "activity_conditioned", "activity_to_cutoff_valid", RED, "Candidate population: A→A vs A→V"),
        ("protocol", "activity_to_cutoff_valid", "cutoff_valid", GREEN, "Refitting: A→V vs V→V"),
    ]
    marks = {BLUE: ("^", "-", 1.8), RED: ("s", (0, (3, 2)), 1.5), GREEN: ("o", "-", 2.2)}
    for comparison, protocol, reference, color, label in overlap_specs:
        d = oo[
            oo.comparison_type.eq(comparison)
            & oo.protocol.eq(protocol)
            & oo.reference_protocol.eq(reference)
        ].groupby("week_from").jaccard.median()
        marker, dash, width = marks[color]
        axes[0].plot(d.index, d.values, color=color, marker=marker, linestyle=dash,
                     linewidth=width, markersize=3.8, label=label)
    axes[0].set(title="(a) Top-5% decision overlap", xlabel="Landmark week", ylabel="Jaccard agreement", ylim=(0, 1.0))
    axes[0].legend(frameon=False)

    # A->V and V->V are exactly zero at every landmark. The thick-solid under
    # thin-dashed pairing keeps the two coincident series separable instead of
    # rendering them as a single line.
    budget = read_csv(OULAD / "budget_performance.csv")
    for protocol, label in [("cutoff_valid", "$V{\\to}V$"),
                            ("activity_to_cutoff_valid", "$A{\\to}V$"),
                            ("activity_conditioned", "$A{\\to}A$")]:
        d = (budget[budget.protocol.eq(protocol) & budget.budget.eq(0.05)]
             .groupby("week").wasted_budget_rate.median())
        axes[1].plot(d.index, d.values, label=label, **SERIES_STYLE[protocol])
    axes[1].set(title="(b) Noneligible allocation at 5%", xlabel="Landmark week",
                ylabel="Proportion", ylim=(0, 1.0))
    _zero_note(axes[1], "$A{\\to}V$ and $V{\\to}V$ coincide at $0$", y=0.06)
    axes[1].legend(frameon=False, loc="upper left")

    for ax in axes:
        ax.xaxis.set_major_locator(MaxNLocator(integer=True))
        ax.grid(alpha=0.25, linewidth=0.5)
        ax.spines[["top", "right"]].set_visible(False)
    fig.tight_layout(w_pad=2.0)
    save(fig, "fig4_decision_distortion")

def subgroup_omission() -> None:
    cat = read_csv(OULAD / "excluded_profile_categorical.csv")
    d = cat[cat.week.eq(2)]
    wanted = [
        ("gender", "F", "Women"),
        ("disability", "Y", "Declared disability"),
        ("imd_band", "0-10%", "Most deprived IMD band"),
        ("highest_education", "Lower Than A Level", "Below A-level entry"),
        ("highest_education", "No Formal quals", "No formal qualifications"),
    ]
    rows = []
    for attr, group, label in wanted:
        x = d[d.attribute.eq(attr) & d.group.eq(group)].set_index("observability")
        rows.append(
            {
                "label": label,
                "share_gap": 100 * (x.loc["eligible_silent", "share"] - x.loc["eligible_active", "share"]),
                "risk_gap": 100 * (x.loc["eligible_silent", "risk_rate"] - x.loc["eligible_active", "risk_rate"]),
            }
        )
    frame = pd.DataFrame(rows).sort_values("share_gap")
    y = np.arange(len(frame))
    fig, axes = plt.subplots(1, 2, figsize=(7.16, 2.7), sharey=True)
    axes[0].barh(y, frame.share_gap, color=GREEN)
    axes[0].axvline(0, color="black", linewidth=0.7)
    axes[0].set(title="(a) Representation among silent vs. active", xlabel="Share difference (percentage points)", yticks=y, yticklabels=frame.label)
    axes[1].barh(y, frame.risk_gap, color=ORANGE)
    axes[1].axvline(0, color="black", linewidth=0.7)
    axes[1].set(title="(b) Adverse-outcome concentration", xlabel="Prevalence difference (percentage points)")
    for ax in axes:
        ax.grid(axis="x", alpha=0.25, linewidth=0.5)
        ax.spines[["top", "right"]].set_visible(False)
    fig.tight_layout(w_pad=1.2)
    save(fig, "fig5_subgroup_omission")

def model_heterogeneity() -> None:
    distortion = read_csv(OULAD / "metric_distortion.csv")
    distortion = distortion[
        distortion.metric.eq("auc")
        & distortion.reference_protocol.eq("cutoff_valid")
        & distortion.protocol.isin(["activity_conditioned", "static_full"])
    ]
    order = list(MODEL_LABELS)
    weeks = sorted(distortion.week.unique())
    values = []
    for protocol in ["activity_conditioned", "static_full"]:
        pivot = (
            distortion[distortion.protocol.eq(protocol)]
            .pivot(index="model", columns="week", values="delta")
            .reindex(index=order, columns=weeks)
        )
        values.append(pivot)

    bound = max(abs(min(v.min().min() for v in values)), abs(max(v.max().max() for v in values)))
    norm = TwoSlopeNorm(vmin=-bound, vcenter=0, vmax=bound)
    fig, axes = plt.subplots(1, 2, figsize=(7.16, 3.55), sharey=True)
    titles = ["(a) Activity-conditioned minus valid", "(b) Static-full minus valid"]
    image = None
    for ax, pivot, title in zip(axes, values, titles):
        image = ax.imshow(pivot.values, cmap="RdBu_r", norm=norm, aspect="auto")
        ax.set(
            title=title,
            xlabel="Landmark week",
            xticks=np.arange(len(weeks)),
            xticklabels=weeks,
            yticks=np.arange(len(order)),
            yticklabels=[MODEL_LABELS[m] for m in order],
        )
        ax.tick_params(length=0)
        for x in np.arange(0.5, len(weeks), 1):
            ax.axvline(x, color="white", linewidth=0.5, alpha=0.7)
        for y in np.arange(0.5, len(order), 1):
            ax.axhline(y, color="white", linewidth=0.5, alpha=0.7)
    fig.subplots_adjust(left=0.16, right=0.88, bottom=0.13, top=0.90, wspace=0.08)
    cbar_ax = fig.add_axes([0.91, 0.14, 0.018, 0.72])
    cbar = fig.colorbar(image, cax=cbar_ax)
    cbar.set_label("ROC-AUC difference")
    save(fig, "fig6_model_heterogeneity")


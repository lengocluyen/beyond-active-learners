"""Regenerate OULAD numeric figures from completed TLT result artifacts.

No model is fitted and raw learner data are not required. The three figures
used in the main paper are generated by default; --extra also refreshes the
five supporting numeric figures. Existing conceptual diagrams are untouched.
The default figures need aggregate tables only. Supporting hazard-prevalence
and calibration figures also need locally saved membership and prediction
artifacts from a completed experiment.

Example:
    python3 scripts/regenerate_tlt_figures.py \
        --results tlt_submission_time_v1/main/oulab \
        --output-dir paper_tlt_riskset/figures --extra
"""
